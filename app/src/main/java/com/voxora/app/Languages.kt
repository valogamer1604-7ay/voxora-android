    /** Indian languages first, because most Voxora users are in India. */
    private val featured = listOf("en-IN", "hi-IN", "mr-IN", "bn-IN", "ta-IN", "te-IN", "gu-IN", "kn-IN", "ml-IN", "pa-IN", "ur-IN", "or-IN", "as-IN", "sa-IN", "kok-IN", "mai-IN", "sd-IN", "ks-IN", "doi-IN", "mni-IN", "brx-IN", "sat-IN")

    data class Lang(val tag: String, val english: String, val native: String)

    val all: List<Lang> by lazy {
        val rest = tags.filter { it !in featured }.map { make(it) }.sortedBy { it.english }
        featured.map { make(it) } + rest
    }

    fun make(tag: String): Lang {
        val l = Locale.forLanguageTag(tag)
        val en = l.getDisplayName(Locale.ENGLISH)
        val nat = l.getDisplayName(l).replaceFirstChar { it.uppercase(l) }
        return Lang(tag, en, nat)
    }

    fun resolve(pref: String): String = if (pref == "auto") Locale.getDefault().toLanguageTag() else pref

    fun label(pref: String): String =
        if (pref == "auto") "Phone language (" + make(Locale.getDefault().toLanguageTag()).english + ")" else make(pref).english

    fun isEnglish(pref: String) = resolve(pref).startsWith("en")
